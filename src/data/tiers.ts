// Метка "только сервер": клиентский компонент, импортировавший отсюда значение,
// уронит сборку с внятной ошибкой. Раньше такой импорт молча утаскивал zod
// в браузерный бандл. Типы (import type) меткой не задеваются.
import "server-only";
import { z } from "zod";

/**
 * Категории и восемь тарифов. Цены — прайсовые, без скидки:
 * акционная считается в lib/price.ts.
 *
 * Схемы прогоняются при импорте, поэтому пропущенное поле, нулевая цена
 * или дубль идентификатора роняют сборку с понятным текстом.
 */

const mockRowSchema = z.union([
  z.object({
    kind: z.literal("bar"),
    accent: z.enum(["mint", "cool"]).optional(),
    tall: z.boolean().optional(),
  }),
  z.object({
    kind: z.literal("grid"),
    cols: z.union([z.literal(2), z.literal(3)]),
    filled: z.boolean().optional(),
  }),
  z.object({ kind: z.literal("side") }),
]);

/**
 * Сцены живого макета в окне тарифа. Каждая показывает одну возможность
 * пакета и крутится по кругу, пока окно открыто.
 */
const demoSceneSchema = z.enum([
  "scroll", // одна страница, блоки уезжают при прокрутке
  "form", // форма заявки, отправка в Telegram
  "catalog", // каталог позиций
  "parallax", // слои двигаются с разной скоростью
  "pages", // несколько страниц перелистываются
  "admin", // админка: правка текста без разработчика
  "filters", // фильтры и поиск по каталогу
  "blog", // лента статей
  "account", // личный кабинет клиента
  "dashboard", // аналитический дашборд
]);

const tierSchema = z.object({
  id: z.string().regex(/^[a-z0-9-]+$/, "id только латиницей в нижнем регистре"),
  categoryId: z.enum(["simple", "middle"]),
  title: z.string().min(1),
  term: z.string().min(1),
  gist: z.string().min(1),
  basePrice: z.number().int().positive("цена должна быть больше нуля"),
  includes: z.array(z.string().min(1)).min(1, "список того, что входит, пуст"),
  details: z.array(z.string().min(1)).min(1, "нет развёрнутого описания"),
  demo: z.array(demoSceneSchema).min(1, "нет сцен для живого макета"),
  mock: z.array(mockRowSchema).min(1),
  /** Выделенный пакет: один в категории, залит акцентом. */
  featured: z.boolean().optional(),
  order: z.number().int().nonnegative(),
});

const categorySchema = z.object({
  id: z.enum(["simple", "middle"]),
  title: z.string().min(1),
  note: z.string().min(1),
  /** Короткое описание для плитки раздела. Одно на весь сайт. */
  tileText: z.string().min(1),
  /** Подпись ссылки, ведущей в эту категорию из соседней. */
  crossLabel: z.string().min(1),
  /** Служебная строка над заголовком раздела. */
  eyebrow: z.string().min(1),
  termRange: z.string().min(1),
  hint: z.object({
    /** «Если …» — когда подходит эта категория. */
    title: z.string().min(1),
    stay: z.string().min(1),
    leave: z.string().min(1),
    /** Признаки, по которым человек узнаёт свой случай. */
    signs: z.array(z.string().min(1)).min(3),
  }),
  /** Разговор с заказчиком: от минимума категории к её потолку. Без цен. */
  story: z.array(z.string().min(1)).min(3),
  mock: z.array(mockRowSchema).min(1),
});

